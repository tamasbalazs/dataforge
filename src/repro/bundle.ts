/**
 * Builds the reproducibility bundle from a report: lockfiles, a rebuild
 * script, an optional Dockerfile, checksums, a machine-readable manifest and a
 * human-readable guide. Pure functions; the store writes the result.
 */
import type { Issue, Loc } from "./scan";

export interface RPackage {
  Package: string;
  Version: string;
  Source: string;
  Repository?: string;
  RemoteType?: string;
  RemoteHost?: string;
  RemoteUsername?: string;
  RemoteRepo?: string;
  RemoteRef?: string;
  RemoteSha?: string;
  RemoteUrl?: string;
  direct: boolean;
}

export interface RInfo {
  version: string;
  platform: string;
  os: string;
  repos: Array<{ Name: string; URL: string }>;
  packages: RPackage[];
  missing: string[];
  base: string[];
  renv?: string | null;
  session_info: string;
}

export interface PyPackage {
  name: string;
  version: string;
  direct: boolean;
  module?: string | null;
}

export interface PyInfo {
  version: string;
  implementation: string;
  platform: string;
  executable: string;
  packages: PyPackage[];
  missing: string[];
  stdlib: string[];
  freeze: string[];
}

export interface ReproFile {
  path: string;
  size: number;
  sha256?: string | null;
  role: "code" | "data" | "other";
  referencedBy?: Loc[];
}

export interface LangSection<I> {
  files: string[];
  usage: Record<string, Loc[]>;
  info?: I;
  error?: string;
}

export interface ReproReport {
  root: string;
  name: string;
  createdAt: string;
  app: { version: string; platform: string };
  files: ReproFile[];
  r: LangSection<RInfo> | null;
  python: LangSection<PyInfo> | null;
  missingData: Array<{ ref: string } & Loc>;
  issues: Issue[];
  git: {
    repo: boolean;
    commit?: string | null;
    branch?: string | null;
    dirty: string[];
    remote?: string | null;
  };
  projectLock: { renvLock: boolean; uvLock: boolean; pyproject: boolean };
}

export interface BundleOptions {
  includeCode: boolean;
  includeData: boolean;
  dockerfile: boolean;
  entryPoints: string[];
  locale: "hu" | "en";
}

export interface BundleEntry {
  name: string;
  source?: string;
  text?: string;
  executable?: boolean;
}

