/** renv.lock (version 1 layout); renv::restore() installs exactly these versions. */
export function renvLock(info: RInfo): string {
  const packages: Record<string, unknown> = {};
  for (const p of info.packages) {
    const { direct: _direct, ...rest } = p;
    packages[p.Package] = Object.fromEntries(
      Object.entries(rest).filter(([, v]) => v != null && v !== ""),
    );
  }
  return (
    JSON.stringify(
      {
        R: { Version: info.version, Repositories: info.repos },
        Packages: packages,
      },
      null,
      2,
    ) + "\n"
  );
}

/** Pinned requirements: the imported packages and everything they depend on. */
export function requirementsTxt(info: PyInfo, header: string): string {
  const lines = info.packages.map(
    (p) =>
      `${p.name}==${p.version}${p.direct && p.module && p.module !== p.name ? `  # import ${p.module}` : ""}`,
  );
  return `# ${header}\n# Python ${info.version} (${info.implementation})\n${lines.join("\n")}\n`;
}

export const sh = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

export function runCommand(path: string): string | null {
  if (/\.r$/i.test(path)) return `Rscript --no-save --no-restore ${sh(path)}`;
  if (/\.py$/i.test(path)) return `"$PYBIN" ${sh(path)}`;
  if (/\.qmd$/i.test(path)) return `quarto render ${sh(path)}`;
  if (/\.rmd$/i.test(path))
    return `Rscript -e ${sh(`rmarkdown::render(${JSON.stringify(path)})`)}`;
  if (/\.ipynb$/i.test(path))
    return `"$PYBIN" -m jupyter nbconvert --to notebook --execute --inplace ${sh(path)}`;
  return null;
}

export function reproduceSh(report: ReproReport, opts: BundleOptions): string {
  const r = report.r?.info;
  const py = report.python?.info;
  const L: string[] = [];
  L.push("#!/usr/bin/env bash");
  L.push(
    `# Reproduce "${report.name}" — generated by DataForge ${report.app.version} on ${report.createdAt}.`,
  );
  L.push("# Usage: ./reproduce.sh [--setup-only | --run-only | --check-only]");
  L.push("set -euo pipefail");
  L.push('HERE="$(cd "$(dirname "$0")" && pwd)"');
  L.push('MODE="${1:-all}"');
  L.push('cd "$HERE"');
  L.push("");
  L.push('echo "== 1/4 Checking files (SHA-256)"');
  L.push(
    "if command -v sha256sum >/dev/null 2>&1; then sha256sum --quiet -c checksums.sha256; else shasum -a 256 -q -c checksums.sha256; fi",
  );
  L.push('[ "$MODE" = "--check-only" ] && exit 0');
  L.push("cd project");
  if (r) {
    L.push("");
    L.push(
      `echo "== 2/4 R ${r.version} packages (renv.lock, ${r.packages.length} packages)"`,
    );
    L.push('if [ "$MODE" != "--run-only" ]; then');
    L.push(
      `  have=$(Rscript -e 'cat(paste(R.version$major, R.version$minor, sep="."))')`,
    );
    if (!r.packages.length) {
      L.push(
        `  [ "$have" = ${sh(r.version)} ] || echo "warning: R $have found, the analysis used R ${r.version}" >&2`,
      );
      L.push('  echo "(base R only — nothing to install)"');
      L.push("fi");
    }
    if (r.packages.length) {
      L.push(
        `  [ "$have" = ${sh(r.version)} ] || echo "warning: R $have found, the analysis used R ${r.version}" >&2`,
      );
      L.push("  mkdir -p .r-library");
      L.push(
        `  Rscript -e ${sh(
          `if (!requireNamespace("renv", quietly = TRUE)) install.packages("renv", repos = "https://cloud.r-project.org"); renv::restore(lockfile = "../environment/R/renv.lock", library = ".r-library", prompt = FALSE)`,
        )}`,
      );
      L.push("fi");
      L.push('export R_LIBS="$PWD/.r-library${R_LIBS:+:$R_LIBS}"');
    }
  }
  if (py) {
    L.push("");
    L.push(
      `echo "== 3/4 Python ${py.version} packages (requirements.txt, ${py.packages.length} packages)"`,
    );
    L.push('PYTHON="${PYTHON:-python3}"');
    L.push('if [ "$MODE" != "--run-only" ]; then');
    L.push(
      `  have=$("$PYTHON" -c 'import platform; print(platform.python_version())')`,
    );
    L.push(
      `  [ "$have" = ${sh(py.version)} ] || echo "warning: Python $have found, the analysis used Python ${py.version}" >&2`,
    );
    L.push('  "$PYTHON" -m venv .venv');
    L.push(
      "  .venv/bin/python -m pip install --quiet -r ../environment/python/requirements.txt",
    );
    L.push("fi");
    L.push('PYBIN="$PWD/.venv/bin/python"');
  }
  L.push('[ "$MODE" = "--setup-only" ] && exit 0');
  L.push("");
  L.push('echo "== 4/4 Running the analysis"');
  const cmds = opts.entryPoints
    .map((p) => runCommand(p))
    .filter(Boolean) as string[];
  if (!cmds.length)
    L.push(
      'echo "(no entry point was selected at export — run your scripts here)"',
    );
  for (const [i, c] of cmds.entries()) {
    L.push(`echo "-- ${opts.entryPoints[i]}"`);
    L.push(c);
  }
  L.push('echo "Done."');
  return L.join("\n") + "\n";
}

export function dockerfile(report: ReproReport): string {
  const r = report.r?.info;
  const py = report.python?.info;
  const L: string[] = [
    `# Container for "${report.name}" (DataForge ${report.app.version}, ${report.createdAt})`,
  ];
  if (r) {
    L.push(`FROM rocker/r-ver:${r.version}`);
    if (py) {
      L.push(
        `# The analysis used Python ${py.version}; this installs the distribution's Python 3.`,
      );
      L.push(
        "RUN apt-get update && apt-get install -y --no-install-recommends python3 python3-venv python3-pip && rm -rf /var/lib/apt/lists/*",
      );
    }
  } else {
    L.push(`FROM python:${py?.version ?? "3"}-slim`);
  }
  L.push("WORKDIR /work");
  L.push("COPY . .");
  L.push("RUN ./reproduce.sh --setup-only");
  L.push('CMD ["./reproduce.sh", "--run-only"]');
  return L.join("\n") + "\n";
}

export function manifest(
  report: ReproReport,
  opts: BundleOptions,
  included: ReproFile[],
) {
  return {
    format: "dataforge-repro/1",
    project: report.name,
    createdAt: report.createdAt,
    generator: {
      name: "DataForge",
      version: report.app.version,
      platform: report.app.platform,
    },
    git: report.git,
    r: report.r?.info
      ? {
          version: report.r.info.version,
          platform: report.r.info.platform,
          os: report.r.info.os,
          packages: report.r.info.packages.length,
          direct: report.r.info.packages
            .filter((p) => p.direct)
            .map((p) => `${p.Package}@${p.Version}`),
        }
      : null,
    python: report.python?.info
      ? {
          version: report.python.info.version,
          implementation: report.python.info.implementation,
          platform: report.python.info.platform,
          packages: report.python.info.packages.length,
          direct: report.python.info.packages
            .filter((p) => p.direct)
            .map((p) => `${p.name}==${p.version}`),
        }
      : null,
    entryPoints: opts.entryPoints,
    files: included.map((f) => ({
      path: f.path,
      size: f.size,
      sha256: f.sha256 ?? null,
      role: f.role,
    })),
    excludedData: opts.includeData
      ? []
      : report.files
          .filter((f) => f.role === "data")
          .map((f) => ({
            path: f.path,
            size: f.size,
            sha256: f.sha256 ?? null,
          })),
    issues: report.issues.map((i) => ({
      kind: i.kind,
      severity: i.severity,
      file: i.file,
      line: i.line,
      detail: i.detail,
    })),
  };
}

