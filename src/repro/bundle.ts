const human = (n: number) =>
  n < 1024
    ? `${n} B`
    : n < 1048576
      ? `${(n / 1024).toFixed(1)} KB`
      : `${(n / 1048576).toFixed(1)} MB`;

export function readme(
  report: ReproReport,
  opts: BundleOptions,
  issueText: (i: Issue) => string,
): string {
  const t = T[opts.locale];
  const r = report.r?.info;
  const py = report.python?.info;
  const L: string[] = [
    `# ${t.title}: ${report.name}`,
    "",
    t.intro(report.name, report.createdAt.slice(0, 10)),
    "",
  ];
  L.push(
    `## ${t.quick}`,
    "",
    t.quickBody,
    "",
    "```bash",
    "./reproduce.sh",
    "```",
    "",
  );
  if (opts.dockerfile)
    L.push(
      t.docker,
      "",
      "```bash",
      `docker build -t ${report.name.toLowerCase().replace(/[^a-z0-9]+/g, "-")} .`,
      `docker run --rm ${report.name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
      "```",
      "",
    );
  L.push(`## ${t.env}`, "", `| ${t.tool} | ${t.version} |`, "|---|---|");
  if (r)
    L.push(
      `| R | ${r.version} (${r.platform}) — ${r.packages.length} ${t.pkgs} |`,
    );
  if (py)
    L.push(
      `| Python | ${py.version} (${py.implementation}) — ${py.packages.length} ${t.pkgs} |`,
    );
  L.push(`| DataForge | ${report.app.version} |`, "");
  const direct = [
    ...(r?.packages
      .filter((p) => p.direct)
      .map(
        (p) =>
          `R: ${p.Package} ${p.Version}${p.Source !== "Repository" ? ` (${p.Source})` : ""}`,
      ) ?? []),
    ...(py?.packages
      .filter((p) => p.direct)
      .map((p) => `Python: ${p.name} ${p.version}`) ?? []),
  ];
  if (direct.length)
    L.push(`### ${t.direct}`, "", ...direct.map((d) => `- ${d}`), "");
  const data = report.files.filter((f) => f.role === "data");
  if (data.length) {
    L.push(`## ${t.data}`, "");
    if (!opts.includeData) L.push(t.dataExcluded, "");
    L.push(
      "| path | size | sha256 |",
      "|---|---|---|",
      ...data.map(
        (f) =>
          `| \`${f.path}\` | ${human(f.size)} | \`${(f.sha256 ?? "").slice(0, 16)}…\` |`,
      ),
      "",
    );
  }
  if (report.git.repo && report.git.commit) {
    L.push(
      `## ${t.git}`,
      "",
      t.gitLine(report.git.commit.slice(0, 12), report.git.branch ?? "—"),
    );
    if (report.git.dirty.length)
      L.push("", t.gitDirty(report.git.dirty.length));
    L.push("");
  }
  if (report.issues.length)
    L.push(
      `## ${t.issues}`,
      "",
      ...report.issues.map((i) => `- ${issueText(i)}`),
      "",
    );
  L.push(`## ${t.files}`, "", t.filesBody, "");
  return L.join("\n");
}

/** Everything that goes into the bundle, under one top-level folder. */
export function bundleEntries(
  report: ReproReport,
  opts: BundleOptions,
  top: string,
  issueText: (i: Issue) => string,
): BundleEntry[] {
  const join = (p: string) => `${report.root.replace(/[\\/]+$/, "")}/${p}`;
  const included = report.files.filter((f) =>
    f.role === "data" ? opts.includeData : opts.includeCode,
  );
  const out: BundleEntry[] = included.map((f) => ({
    name: `${top}/project/${f.path}`,
    source: join(f.path),
  }));
  const r = report.r?.info;
  const py = report.python?.info;
  if (r) {
    out.push({ name: `${top}/environment/R/renv.lock`, text: renvLock(r) });
    out.push({
      name: `${top}/environment/R/sessionInfo.txt`,
      text: r.session_info + "\n",
    });
  }
  if (py) {
    out.push({
      name: `${top}/environment/python/requirements.txt`,
      text: requirementsTxt(
        py,
        `${report.name} — DataForge ${report.app.version}, ${report.createdAt}`,
      ),
    });
    out.push({
      name: `${top}/environment/python/pip-freeze.txt`,
      text: py.freeze.join("\n") + "\n",
    });
    out.push({
      name: `${top}/environment/python/python-version.txt`,
      text: py.version + "\n",
    });
  }
  if (opts.dockerfile && (r || py))
    out.push({ name: `${top}/Dockerfile`, text: dockerfile(report) });
  // Checksums cover every file the rerun needs — data too, even when it is shipped separately.
  const checked = report.files.filter(
    (f) => f.sha256 && (f.role === "data" || opts.includeCode),
  );
  out.push({
    name: `${top}/checksums.sha256`,
    text:
      checked.map((f) => `${f.sha256}  project/${f.path}`).join("\n") + "\n",
  });
  out.push({
    name: `${top}/reproduce.sh`,
    text: reproduceSh(report, opts),
    executable: true,
  });
  out.push({
    name: `${top}/manifest.json`,
    text: JSON.stringify(manifest(report, opts, included), null, 2) + "\n",
  });
  out.push({
    name: `${top}/${opts.locale === "hu" ? "REPRODUKALAS.md" : "REPRODUCE.md"}`,
    text: readme(report, opts, issueText),
  });
  return out;
}

export function bundleName(name: string, date: Date): string {
  const slug =
    name
      .normalize("NFD")
      .replace(/[̀-ͯ]/g, "")
      .replace(/[^A-Za-z0-9._-]+/g, "-")
      .replace(/^-+|-+$/g, "") || "project";
  const d = date.toISOString().slice(0, 10).replace(/-/g, "");
  return `${slug}-repro-${d}`;
}
